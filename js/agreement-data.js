  // טקסט → HTML: **מודגש** ושדות {{key|____}} (ממולאים מ-vals אם יש ערך)
  function inline(s, vals) {
    var out = '', last = 0, m;
    var src = String(s);
    SLOT.lastIndex = 0;
    while ((m = SLOT.exec(src))) {
      out += esc(src.slice(last, m.index));
      var v = vals && vals[m[1]];
      out += v ? '<span class="agr-fill">' + esc(v) + '</span>' : esc(m[2]);
      last = m.index + m[0].length;
    }
    out += esc(src.slice(last));
    return out.replace(/\*\*([\s\S]+?)\*\*/g, '<strong>$1</strong>');
  }

  /* ---------- טקסט קנוני (Markdown) — זה מה שנכנס ל-SHA-256 ול-docs/agreement-he-v1.md ---------- */
  function toMarkdown() {
    var L = [];
    BLOCKS.forEach(function (b) {
      switch (b.t) {
        case 'title': L.push('# ' + plain(b.text), ''); break;
        case 'sub': L.push(plain(b.text), ''); break;
        case 'warn': case 'callout': L.push('> ' + plain(b.text), ''); break;
        case 'h': L.push('## ' + plain(b.text), ''); break;
        case 'p': L.push(plain(b.text), ''); break;
        case 'small': L.push(plain(b.text), ''); break;
        case 'office': L.push('_' + plain(b.text) + '_', ''); break;
        case 'parties': b.rows.forEach(function (r) { L.push('**' + r.label + '** ' + r.lines.map(plain).join(' ')); }); L.push(''); break;
        case 'ol': b.items.forEach(function (it, i) { L.push((i + 1) + '. ' + plain(it)); }); L.push(''); break;
        case 'table': L.push('| | |', '|---|---|'); b.rows.forEach(function (r) { L.push('| ' + plain(r[0]) + ' | ' + plain(r[1]) + ' |'); }); L.push(''); break;
        case 'docs': b.items.forEach(function (d) {
          L.push('**' + d.n + ' ' + d.title + '** — ' + d.text, '', '☐ עומד/ת בתנאי · העלאת מסמך: ' + d.upload + ' PDF / JPG / PNG · עד 5MB · שם הקובץ שצורף: _____________________', '');
        }); break;
        case 'sign': L.push('| ' + b.cols.join(' | ') + ' |', '|---|---|'); b.rows.forEach(function (r) { L.push('| ' + r[0] + ' | ' + r[1] + ' |'); }); L.push(''); break;
      }
    });
    return L.join('\n').replace(/\n{3,}/g, '\n\n').trim() + '\n';
  }

  /* ---------- HTML ממולא (שלב 3 באתר + הקובץ החתום בשרת) ----------
     d: { entityType, fullName, idNumber, contact, phone, email, address, fields, regions, license, employees,
          city, day, month, year, signerName, signerRole, signDate, signature (data-URL / URL של PNG) } */
  function toHtml(d) {
    d = d || {};
    var H = [];
    BLOCKS.forEach(function (b) {
      switch (b.t) {
        case 'title': H.push('<h2 class="agr-title">' + inline(b.text) + '</h2>'); break;
        case 'sub': H.push('<p class="agr-sub">' + inline(b.text) + '</p>'); break;
        case 'warn': H.push('<p class="agr-warn">' + inline(b.text) + '</p>'); break;
        case 'callout': H.push('<p class="agr-callout">' + inline(b.text) + '</p>'); break;
        case 'h': H.push('<h3 class="agr-h">' + inline(b.text) + '</h3>'); break;
        case 'p': H.push('<p class="agr-p' + (b.strong ? ' agr-strong' : '') + '">' + inline(b.text, d) + '</p>'); break;
        case 'small': H.push('<p class="agr-small">' + inline(b.text) + '</p>'); break;
        case 'office': H.push('<p class="agr-office">' + inline(b.text) + '</p>'); break;
        case 'parties':
          H.push('<table class="agr-table agr-parties"><tbody>' + b.rows.map(function (r) {
            return '<tr><th>' + esc(r.label) + '</th><td>' + r.lines.map(function (l) { return '<div>' + inline(l) + '</div>'; }).join('') + '</td></tr>';
          }).join('') + '</tbody></table>');
          break;
        case 'ol':
          H.push('<ol class="agr-ol">' + b.items.map(function (it) { return '<li>' + inline(it) + '</li>'; }).join('') + '</ol>');
          break;
        case 'table':
          H.push('<table class="agr-table"><tbody>' + b.rows.map(function (r) {
            var key = r[2], val = '';
            if (key && key !== 'payment' && d[key]) { val = '<span class="agr-fill">' + esc(d[key]) + '</span>'; }
            var cell = val || inline(r[1]);
            if (key === 'payment') { cell = (r[1] ? inline(r[1]) + '<br>' : '') + '<span class="agr-pay-note">' + esc(PAY_NOTE) + '</span>'; }
            if (key === 'entityType' && d.entityType) { cell = '<span class="agr-fill">' + esc(d.entityType) + '</span>'; }
            return '<tr><th>' + inline(r[0]) + '</th><td>' + cell + '</td></tr>';
          }).join('') + '</tbody></table>');
          break;
        case 'docs':
          H.push('<div class="agr-docs">' + b.items.map(function (x) {
            var up = d.docs && d.docs[x.n];
            return '<div class="agr-doc"><span class="agr-doc-n">' + x.n + '</span><div><strong>' + esc(x.title) + '</strong><div>' + inline(x.text) + '</div>' +
              '<div class="agr-doc-up">' + (up ? '☑ עומד/ת בתנאי · שם הקובץ שצורף: <span class="agr-fill" dir="auto">' + esc(up) + '</span>'
                : '☐ עומד/ת בתנאי · העלאת מסמך: ' + esc(x.upload) + ' PDF / JPG / PNG · עד 5MB') + '</div></div></div>';
          }).join('') + '</div>');
          break;
        case 'sign':
          H.push('<table class="agr-table agr-sign"><thead><tr><th>' + esc(b.cols[0]) + '</th><th>' + esc(b.cols[1]) + '</th></tr></thead><tbody>' + b.rows.map(function (r) {
            var k = r[2], v = d[k];
            var mine = k === 'signature'
              ? (v ? '<img class="agr-sig" alt="חתימת קבלן הבית" src="' + esc(v) + '">' : esc(r[0]))
              : (v ? esc(r[0]) + ': <span class="agr-fill">' + esc(v) + '</span>' : esc(r[0]));
            return '<tr><td>' + mine + '</td><td class="agr-company">' + esc(r[1]) + '</td></tr>';
          }).join('') + '</tbody></table>');
          break;
      }
    });
    return H.join('\n');
  }

